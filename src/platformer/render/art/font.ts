export const GLYPH_W = 5
export const GLYPH_H = 7
export const GLYPH_ADVANCE = 6

/** A text bitmap with a 1-pixel dark outline so it reads on any background. */
export function textBitmap(text: string, color: string, outline = '#1d1a2e'): Bitmap {
  const s = text.toUpperCase().replace(/×/g, 'x')
  const b = new Bitmap(Math.max(1, s.length * GLYPH_ADVANCE + 1), GLYPH_H + 2)
  const c = hex(color)
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS[s[i]] ?? GLYPHS['?']
    for (let y = 0; y < GLYPH_H; y++) for (let x = 0; x < GLYPH_W; x++) if (g[y][x] === '#') b.set(1 + i * GLYPH_ADVANCE + x, 1 + y, c)
  }
  return b.outlined(outline)
}
